async function login(page,username='accept-editor'){
 await page.goto('/actions');
 await page.getByLabel('账号',{exact:true}).fill(username);
 await page.getByLabel('密码',{exact:true}).fill(process.env.ACCEPTANCE_PASSWORD);
 await page.getByRole('button',{name:'登录',exact:true}).click();
 await expect(page.getByRole('heading',{name:'标准动作配置',exact:true})).toBeVisible();
}
async function switchUser(page,username){await page.getByRole('button',{name:'退出登录'}).click();await login(page,username);}
