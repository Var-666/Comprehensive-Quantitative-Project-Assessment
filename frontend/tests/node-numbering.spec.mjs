import { test, expect } from '@playwright/test';
import { choose } from './ui-controls.mjs';

test('node form allocates sequential codes on save and retains manual codes and immutable edits', async ({ page }) => {
  await page.goto('/projects');
  await page.getByLabel('账号', { exact: true }).fill('accept-editor');
  await page.getByLabel('密码', { exact: true }).fill(process.env.ACCEPTANCE_PASSWORD);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '项目管理', exact: true })).toBeVisible();
  const identity = (await (await page.request.get('/api/v1/auth/me')).json()).data;
  const created = await page.request.post('/api/v1/projects', { headers: { 'X-CSRF-Token': identity.csrf_token }, data: { project_code: 'P-H099', project_name: '自动编号界面验收', project_status: 'draft' } });
  expect(created.status()).toBe(201);
  const project = (await created.json()).data;
  await page.reload();
  await page.goto(`/milestones?project=${project.id}`);
  const table = page.locator('.milestone-list-table');
  for (const [index, manual] of [undefined, undefined, 'MANUAL-CODE'].entries()) {
    await page.getByRole('button', { name: '添加节点', exact: true }).first().click();
    const form = page.getByRole('dialog', { name: '新增项目节点', exact: true });
    const code = form.getByLabel('节点编号', { exact: true });
    await expect(code).toHaveValue('');
    await expect(code).toHaveAttribute('placeholder', '自动生成（可手动填写）');
    expect(await code.getAttribute('required')).toBeNull();
    if (manual) await code.fill(manual);
    await form.getByLabel('节点名称 *', { exact: true }).fill(`自动编号验收节点 ${index + 1}`);
    await choose(form.getByLabel('节点类型 *', { exact: true }), '设计资料');
    await form.getByLabel('计划完成日期 *', { exact: true }).fill('2026-11-01');
    await form.getByLabel('计划完成日期 *', { exact: true }).press('Tab');
    await expect(form.getByLabel('变更原因 *', { exact: true })).toHaveCount(0);
    const saved = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === `/api/v1/projects/${project.id}/milestones`);
    await form.getByRole('button', { name: '保存节点', exact: true }).click();
    const result = await saved;
    expect(result.status()).toBe(201);
    const node = (await result.json()).data;
    expect(node.milestone_code).toBe(manual || `H099-N00${index + 1}`);
    const payload = result.request().postDataJSON();
    if (!manual) expect(payload).not.toHaveProperty('milestone_code');
    expect(payload).not.toHaveProperty('change_reason');
    expect(node.plan_item.change_reason).toBe('新增节点');
    await expect(form).toHaveCount(0);
    await expect(page.getByRole('heading', { name: '节点配置结果', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '返回节点列表', exact: true }).click();
    await expect(table).toContainText(node.milestone_code);
  }
  await page.reload();
  await expect(table.locator('tbody tr')).toHaveCount(3);
  await table.getByRole('row').filter({ hasText: 'H099-N001' }).getByRole('button', { name: '编辑', exact: true }).click();
  const edit = page.getByRole('dialog', { name: '编辑节点计划草稿', exact: true });
  await expect(edit.getByLabel('节点编号', { exact: true })).toHaveAttribute('readonly', '');
  await expect(edit.getByLabel('节点编号', { exact: true })).toHaveValue('H099-N001');
  await edit.getByLabel('节点名称 *', { exact: true }).fill('修改名称保留自动编号');
  expect(await edit.getByLabel('变更原因 *', { exact: true }).getAttribute('required')).not.toBeNull();
  await edit.getByRole('button', { name: '保存节点', exact: true }).click();
  await expect(edit).toBeVisible();
  expect(await edit.locator('#node-form').evaluate(form => form.checkValidity())).toBe(false);
  await edit.getByLabel('变更原因 *', { exact: true }).fill('只修改名称');
  await edit.getByRole('button', { name: '保存节点', exact: true }).click();
  await expect(edit).toHaveCount(0);
  await expect(table.getByRole('row').filter({ hasText: 'H099-N001' })).toContainText('修改名称保留自动编号');
});
